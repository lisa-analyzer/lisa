package it.unive.lisa.triage.model;

import it.unive.lisa.analysis.AbstractDomain;
import it.unive.lisa.analysis.AbstractLattice;
import it.unive.lisa.analysis.AnalysisState;
import it.unive.lisa.analysis.SemanticException;
import it.unive.lisa.analysis.SemanticOracle;
import it.unive.lisa.analysis.SimpleAbstractDomain;
import it.unive.lisa.analysis.value.ValueDomain;
import it.unive.lisa.analysis.value.ValueLattice;
import it.unive.lisa.interprocedural.ScopeId;
import it.unive.lisa.lattices.SimpleAbstractState;
import it.unive.lisa.program.cfg.ProgramPoint;
import it.unive.lisa.symbolic.SymbolicExpression;
import it.unive.lisa.symbolic.value.BinaryExpression;
import it.unive.lisa.symbolic.value.Identifier;
import java.util.Collection;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * Exports the abstract states computed by an analysis as sets of constraints
 * over identifiers, that hold in every concrete state represented by the
 * abstract ones. Constraints are generated by the value domain of the analysis
 * (see
 * {@link ValueDomain#constraints(ValueDomain, ValueLattice, it.unive.lisa.symbolic.value.ValueExpression, ProgramPoint, SemanticOracle)}),
 * and have the form {@code constant OP identifier}. Domains that are not
 * {@link SimpleAbstractDomain}s do not generate constraints.
 *
 * @author <a href="mailto:luca.negrini@unive.it">Luca Negrini</a>
 *
 * @param <A> the type of the abstract states of the analysis
 * @param <D> the type of the domain of the analysis
 */
public class ConstraintExporter<A extends AbstractLattice<A>, D extends AbstractDomain<A>> {

	private final D domain;

	private final ScopeId<?> context;

	/**
	 * Builds the exporter.
	 *
	 * @param domain  the domain of the analysis
	 * @param context the context of the exported states
	 */
	public ConstraintExporter(
			D domain,
			ScopeId<?> context) {
		this.domain = domain;
		this.context = context;
	}

	/**
	 * Exports the given state as constraints over the given identifiers.
	 *
	 * @param state the state, as computed by the analysis
	 * @param ids   the identifiers to constrain
	 * @param pp    the program point where the state holds
	 *
	 * @return the constraints, or {@code null} if the state does not represent
	 *             any concrete state (i.e., the program point is unreachable)
	 *
	 * @throws SemanticException if something goes wrong while generating the
	 *                               constraints
	 */
	@SuppressWarnings({ "unchecked", "rawtypes" })
	public Set<SymbolicExpression> constraints(
			AnalysisState<A> state,
			Collection<Identifier> ids,
			ProgramPoint pp)
			throws SemanticException {
		if (state.getExecution().isBottom())
			return null;

		Set<SymbolicExpression> result = new LinkedHashSet<>();
		A exec = state.getExecutionState();
		if (!(domain instanceof SimpleAbstractDomain) || !(exec instanceof SimpleAbstractState))
			return result;

		ValueDomain valueDomain = ((SimpleAbstractDomain) domain).valueDomain;
		ValueLattice valueState = ((SimpleAbstractState) exec).valueState;
		SemanticOracle oracle = domain.makeOracle(exec, context);
		for (Identifier id : ids) {
			if (!exec.knowsIdentifier(id))
				continue;
			Set<BinaryExpression> cs = valueDomain.constraints(null, valueState, id, pp, oracle);
			if (cs == null)
				return null;
			result.addAll(cs);
		}
		return result;
	}
}
